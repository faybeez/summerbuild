--   ON public.ootd_entries(event_id);

-- Policies
ALTER TABLE public.ootd_entries ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS ootd_entries_crud_own_data ON public.ootd_entries;

CREATE POLICY ootd_entries_crud_own_data
ON public.ootd_entries
FOR ALL
TO authenticated
USING (auth.uid() = user_id)
WITH CHECK (auth.uid() = user_id);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.ootd_entries TO authenticated;